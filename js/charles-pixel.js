/**
 * 머리 위 응원 배너 렌더러
 * - 검정색 테두리 없이 산뜻하고 화사한 테마 전용 보더 & 파스텔 배경
 * - 찰스 머리 위로 시원하게 둥둥 뜨는 플로팅 배너 (지지대 없이 깔끔한 연출)
 * - 친구 화면에서도 또렷하게 읽히는 초대형 900 Black 폰트 (y: -6.0 ~ -1.2)
 */
function renderAccessoryHeaderBanner(itemId, scale) {
  const theme = (typeof PRAISE_BANNER_THEMES !== 'undefined') ? PRAISE_BANNER_THEMES[itemId] : null;
  if (!theme) return '';

  let r = '';

  // 1. 검정 테두리 없는 산뜻하고 세련된 테마 전용 컨테이너 (x: 0.5~23.5, y: -6.0 ~ -1.2, width: 23, height: 4.8)
  r += `<rect x="${0.5 * scale}" y="${-6.0 * scale}" width="${23.0 * scale}" height="${4.8 * scale}" rx="${0.6 * scale}" fill="${theme.bg}" stroke="${theme.border}" stroke-width="${0.75 * scale}" />`;

  // 2. 상/하단 은은한 마이크로 하이라이트 액센트
  r += `<rect x="${1.2 * scale}" y="${-5.6 * scale}" width="${21.6 * scale}" height="${0.25 * scale}" fill="${theme.border}" opacity="0.35" />`;
  r += `<rect x="${1.2 * scale}" y="${-1.65 * scale}" width="${21.6 * scale}" height="${0.25 * scale}" fill="${theme.border}" opacity="0.35" />`;

  // 3. 좌우 미니멀 리본 팁 포인트 (테마 색상)
  r += `<rect x="${0.1 * scale}" y="${-3.9 * scale}" width="${0.6 * scale}" height="${1.0 * scale}" fill="${theme.border}" />`;
  r += `<rect x="${23.3 * scale}" y="${-3.9 * scale}" width="${0.6 * scale}" height="${1.0 * scale}" fill="${theme.border}" />`;

  // 4. 찬양 이름 텍스트 렌더링 (글자 크기 한 번 더 대폭 확대, 가독성 극대화)
  let fontSize = scale * 1.6;
  let letterSpacing = '-0.2px';
  if (theme.title.length <= 4) {
    fontSize = scale * 2.85;
  } else if (theme.title.length <= 7) {
    fontSize = scale * 2.45;
  } else if (theme.title.length <= 9) {
    fontSize = scale * 2.15;
  } else if (theme.title.length <= 11) {
    fontSize = scale * 1.85;
    letterSpacing = '-0.35px';
  } else {
    // 12자 이상 (예: 우리가 주를 더욱 사랑하고)
    fontSize = scale * 1.6;
    letterSpacing = '-0.45px';
  }

  // Y축 정중앙 (-6.0 + 4.8 / 2 = -3.6)에 맞춘 완벽 수직 센터링
  r += `<text x="${12 * scale}" y="${-3.5 * scale}" font-family="'Pretendard', 'Apple SD Gothic Neo', 'Noto Sans KR', sans-serif" font-size="${fontSize}px" font-weight="900" text-anchor="middle" dominant-baseline="middle" fill="${theme.text}" letter-spacing="${letterSpacing}">${theme.title}</text>`;

  return r;
}

/**
 * 아이템별 상점/옷장 전용 고화질 픽셀 SVG 아이콘 생성
 */
function getAccessoryIconSvg(itemId) {
  if (itemId === 'head_straw_hat') {
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="4.5 1.5 15 5" class="pixel-item-svg" shape-rendering="crispEdges">${renderAccessoryStrawHat(1)}</svg>`;
  } else if (itemId === 'head_glasses') {
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="5.5 8.5 11 4" class="pixel-item-svg" shape-rendering="crispEdges">${renderAccessoryGlasses(1)}</svg>`;
  } else if (itemId === 'hold_bible') {
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="14.5 10.5 5 6" class="pixel-item-svg" shape-rendering="crispEdges">${renderAccessoryBible(1)}</svg>`;
  } else if (itemId === 'back_daisy_field') {
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="1.5 14.5 20 6" class="pixel-item-svg" shape-rendering="crispEdges">${renderAccessoryDaisyField(1)}</svg>`;
  } else if (itemId && itemId.startsWith('banner_')) {
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -6.5 24 6.5" class="pixel-item-svg" shape-rendering="crispEdges">${renderAccessoryHeaderBanner(itemId, 1)}</svg>`;
  } else if (typeof AUTUMN_ITEM_PIXELS !== 'undefined' && AUTUMN_ITEM_PIXELS[itemId]) {
    const b = AUTUMN_ITEM_PIXELS[itemId].bounds;
    const pad = 1;
    const vb = (b.minX - pad) + ' ' + (b.minY - pad) + ' ' + (b.maxX - b.minX + pad * 2 + 1) + ' ' + (b.maxY - b.minY + pad * 2 + 1);
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" class="pixel-item-svg" shape-rendering="crispEdges">${renderAutumnAccessory(itemId, 1)}</svg>`;
  } else if (typeof CHURCH_BG_ITEM_PIXELS !== 'undefined' && CHURCH_BG_ITEM_PIXELS[itemId]) {
    const pxs = CHURCH_BG_ITEM_PIXELS[itemId].pixels || CHURCH_BG_ITEM_PIXELS[itemId];
    if (pxs && pxs.length > 0) {
      let minX = 999, maxX = -999, minY = 999, maxY = -999;
      for (let i = 0; i < pxs.length; i++) {
        const x = pxs[i][0];
        const y = pxs[i][1];
        const sz = pxs[i][3] || 1;
        if (x < minX) minX = x;
        if (x + sz > maxX) maxX = x + sz;
        if (y < minY) minY = y;
        if (y + sz > maxY) maxY = y + sz;
      }
      const pad = 0.8;
      const vb = (minX - pad) + ' ' + (minY - pad) + ' ' + (maxX - minX + pad * 2) + ' ' + (maxY - minY + pad * 2);
      return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" class="pixel-item-svg" shape-rendering="crispEdges">${renderPixelArrayGeneric(pxs, 1)}</svg>`;
    }
  } else if (typeof PRAISE_MUSIC_ITEM_PIXELS !== 'undefined' && PRAISE_MUSIC_ITEM_PIXELS[itemId]) {
    const pxs = PRAISE_MUSIC_ITEM_PIXELS[itemId].pixels || PRAISE_MUSIC_ITEM_PIXELS[itemId];
    if (pxs && pxs.length > 0) {
      let minX = 999, maxX = -999, minY = 999, maxY = -999;
      for (let i = 0; i < pxs.length; i++) {
        const x = pxs[i][0];
        const y = pxs[i][1];
        const sz = pxs[i][3] || 1;
        if (x < minX) minX = x;
        if (x + sz > maxX) maxX = x + sz;
        if (y < minY) minY = y;
        if (y + sz > maxY) maxY = y + sz;
      }
      const pad = 1;
      const vb = (minX - pad) + ' ' + (minY - pad) + ' ' + (maxX - minX + pad * 2) + ' ' + (maxY - minY + pad * 2);
      return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" class="pixel-item-svg" shape-rendering="crispEdges">${renderPixelArrayGeneric(pxs, 1)}</svg>`;
    }
  }
  return '';
}

/**
 * 범용 픽셀 배열 SVG rect 렌더러 (4번째 요소 size 서브픽셀 스케일 지원)
 */
function renderPixelArrayGeneric(pixels, scale) {
  if (!pixels || !Array.isArray(pixels)) return '';
  let res = '';
  for (let i = 0; i < pixels.length; i++) {
    const p = pixels[i];
    const sz = p[3] || 1;
    res += `<rect x="${p[0] * scale}" y="${p[1] * scale}" width="${sz * scale}" height="${sz * scale}" fill="${p[2]}" />`;
  }
  return res;
}

/**
 * 24x24 통일 규격 찰스 메인 픽셀 그리드 렌더러
 * (배너 착용 시 상단 공간을 자동으로 확장하여 높은 배너를 완벽하게 포용)
 */
function renderSimplePixelGrid(stageOrRows, scale = 9, animClass = 'charles-static', equipped = {}) {
  // 캔버스 크기: 24x24 (배너 착용 여부에 따라 상단 여백 동적 확장)
  const hasBanner = !!(equipped && (equipped.banner || (equipped.hold && String(equipped.hold).startsWith('banner_'))));
  const bannerId = hasBanner ? (equipped.banner || equipped.hold) : null;
  const hasChurchBg = !!(equipped && ((equipped.back && String(equipped.back).startsWith('church_seowonkyung_')) || (equipped.grass && String(equipped.grass).startsWith('church_seowonkyung_')) || (equipped.side && String(equipped.side).includes('church_'))));
  const hasLeftFullChurch = !!(equipped && equipped.side && (equipped.side === 'side_church_full_left' || equipped.side === 'side_church_glow_full_left'));

  const canvasWidth = 24;
  const canvasHeight = 24;
  const leftPaddingGrid = hasLeftFullChurch ? 10.0 : 0;
  const svgWidth = Math.round((canvasWidth + leftPaddingGrid) * scale);
  const svgHeight = canvasHeight * scale;
  const viewBoxMinX = Math.round(-leftPaddingGrid * scale);

  // 머리 위 배너, 모자, 왕관, 서원경교회 종탑 십자가가 위쪽으로 잘리지 않도록 넉넉한 상단 헤드룸 동적 확보
  let topPaddingGrid = 3.5; // 기본 상단 여백 (모자, 왕관 y:0, 귀도리 등 상단 천장 닿음 방지)
  if (hasBanner) {
    topPaddingGrid = 8.5; // 배너 착용 시 상단 여백 대폭 확장 (배너가 -6.0에 위치하므로 2.5 그리드 완전 여유)
  } else if (hasChurchBg) {
    topPaddingGrid = 5.5; // 서원경교회 3D 조감도 종탑 십자가(y:-4.5) 상단 여유 확보
  } else if (equipped && (equipped.back === 'back_melody_aura' || equipped.grass === 'back_melody_aura')) {
    topPaddingGrid = 4.5; // 찬양 음표 아우라 착용 시 상단 여백 추가 확보
  }
  const bottomPaddingGrid = 1.5; // 하단 바닥 잔디/그림자 여유 공간
  const viewBoxMinY = Math.round(-topPaddingGrid * scale);
  const viewBoxHeight = Math.round((canvasHeight + topPaddingGrid + bottomPaddingGrid) * scale);

  // Layer 1: Back / Floor 악세사리 (바닥 잔디/낙엽/눈밭/천사날개/멜로디아우라)
  let backRects = '';
  if (equipped) {
    if (equipped.grass === 'back_maple_carpet' || equipped.back === 'back_maple_carpet' || (equipped.grass === undefined && equipped.back === undefined && equipped.back_maple_carpet)) {
      backRects += renderAutumnAccessory('back_maple_carpet', scale);
    } else if (equipped.grass === 'back_daisy_field' || equipped.back === 'back_daisy_field' || (equipped.grass === undefined && equipped.back === undefined && equipped.back_daisy_field)) {
      backRects += renderAccessoryDaisyField(scale);
    } else {
      const backItem = equipped.back || equipped.grass;
      if (backItem && typeof getAnyItemPixels === 'function' && getAnyItemPixels(backItem)) {
        backRects += renderPixelArrayGeneric(getAnyItemPixels(backItem), scale);
      }
    }
  }

  // Layer 1.5: Side 소품 (스탠드 마이크, 신디사이저, 단호박, 눈사람, 선물상자 등)
  let sideRects = '';
  if (equipped) {
    if (equipped.side === 'side_autumn_pumpkin' || (equipped.side === undefined && (equipped.hold === 'side_autumn_pumpkin' || equipped.side_autumn_pumpkin))) {
      sideRects += renderAutumnAccessory('side_autumn_pumpkin', scale);
    } else if (equipped.side && typeof getAnyItemPixels === 'function' && getAnyItemPixels(equipped.side)) {
      sideRects += renderPixelArrayGeneric(getAnyItemPixels(equipped.side), scale);
    }
  }

  // Layer 2: 찰스 본체 (공식 신규 1~5단계 정밀 픽셀 데이터)
  let bodyRects = '';
  let currentStage = 1;
  if (typeof stageOrRows === 'number') {
    currentStage = Math.max(1, Math.min(5, Math.floor(stageOrRows)));
  } else if (Array.isArray(stageOrRows)) {
    currentStage = 1;
  }

  const stagePixels = (typeof CHARLES_NEW_STAGES !== 'undefined') ? CHARLES_NEW_STAGES[currentStage] : null;
  if (stagePixels && Array.isArray(stagePixels)) {
    for (let i = 0; i < stagePixels.length; i++) {
      const px = stagePixels[i];
      bodyRects += `<rect x="${px[0] * scale}" y="${px[1] * scale}" width="${scale}" height="${scale}" fill="${px[2]}" />`;
    }
  }

  // Layer 2.5: Neck 악세사리 (도토리 니트 목도리, 체크 목도리 등)
  let neckRects = '';
  if (equipped) {
    if (equipped.neck === 'neck_acorn_scarf' || (equipped.neck === undefined && equipped.neck_acorn_scarf)) {
      neckRects += renderAutumnAccessory('neck_acorn_scarf', scale);
    } else if (equipped.neck && typeof getAnyItemPixels === 'function' && getAnyItemPixels(equipped.neck)) {
      neckRects += renderPixelArrayGeneric(getAnyItemPixels(equipped.neck), scale);
    }
  }

  // Layer 3: Glasses 악세사리 (둥근 범생이 안경)
  let glassesRects = '';
  if (equipped) {
    if (equipped.glasses === 'head_glasses' || (equipped.glasses === undefined && (equipped.head === 'head_glasses' || equipped.body === 'head_glasses' || equipped.head_glasses))) {
      glassesRects += renderAccessoryGlasses(scale, 0);
    } else if (equipped.glasses && typeof getAnyItemPixels === 'function' && getAnyItemPixels(equipped.glasses)) {
      glassesRects += renderPixelArrayGeneric(getAnyItemPixels(equipped.glasses), scale);
    }
  }

  // Layer 4: Head 악세사리 (밀짚모자, 단풍베레모, 헤드폰, 황금면류관, 산타모자, 귀도리)
  let headRects = '';
  if (equipped) {
    if (equipped.head === 'head_maple_beret' || (equipped.head === undefined && equipped.head_maple_beret)) {
      headRects += renderAutumnAccessory('head_maple_beret', scale);
    } else if (equipped.head === 'head_straw_hat' || (equipped.head === undefined && equipped.head_straw_hat)) {
      headRects += renderAccessoryStrawHat(scale);
    } else if (equipped.head && typeof getAnyItemPixels === 'function' && getAnyItemPixels(equipped.head)) {
      headRects += renderPixelArrayGeneric(getAnyItemPixels(equipped.head), scale);
    }
  }

  // Layer 5: Hold 악세사리 (가로 통기타, 일렉기타, 마이크, 탬버린, 성경책, 랜턴, 바구니)
  let holdRects = '';
  if (equipped) {
    if (equipped.hold === 'hold_autumn_lantern' || (equipped.hold === undefined && equipped.hold_autumn_lantern)) {
      holdRects += renderAutumnAccessory('hold_autumn_lantern', scale);
    } else if (equipped.hold === 'hold_apple_basket' || (equipped.hold === undefined && equipped.hold_apple_basket)) {
      holdRects += renderAutumnAccessory('hold_apple_basket', scale);
    } else if (equipped.hold === 'hold_bible' || (equipped.hold === undefined && (equipped.body === 'hold_bible' || equipped.hold_bible))) {
      holdRects += renderAccessoryBible(scale);
    } else if (equipped.hold && typeof getAnyItemPixels === 'function' && getAnyItemPixels(equipped.hold)) {
      holdRects += renderPixelArrayGeneric(getAnyItemPixels(equipped.hold), scale);
    }
  }

  // Layer 6: Banner 악세사리 (머리 위 13종 찬양 응원 배너)
  let bannerRects = '';
  if (bannerId) {
    bannerRects += renderAccessoryHeaderBanner(bannerId, scale);
  }

  return `
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBoxMinX} ${viewBoxMinY} ${svgWidth} ${viewBoxHeight}" 
         class="charles-svg ${animClass} ${hasBanner ? 'has-charles-banner' : ''}" 
         style="image-rendering: pixelated; shape-rendering: crispEdges; width: 100%; height: auto; max-width: ${hasLeftFullChurch ? '220px' : '150px'}; display: block; margin: 0 auto;">
      <g class="layer-back">${backRects}</g>
      <g class="layer-body">${bodyRects}</g>
      <g class="layer-side">${sideRects}</g>
      <g class="layer-neck">${neckRects}</g>
      <g class="layer-glasses">${glassesRects}</g>
      <g class="layer-head">${headRects}</g>
      <g class="layer-hold">${holdRects}</g>
      <g class="layer-banner">${bannerRects}</g>
    </svg>
  `;
}

/**
 * 단계별 찰스 SVG 그래픽 및 메타 정보 반환
 */
function getCharlesVisual(stage = 1, scale = 9, equipped = null) {
  const safeStage = Math.max(1, Math.min(5, Math.floor(stage)));
  const info = CHARLES_STAGES[safeStage];

  let activeEquipped = equipped;
  if (!activeEquipped && typeof TalentService !== 'undefined' && TalentService.getEquipped) {
    activeEquipped = TalentService.getEquipped();
  }

  const svg = renderSimplePixelGrid(safeStage, scale, 'charles-static', activeEquipped || {});

  return {
    stage: safeStage,
    info,
    svg,
    equipped: activeEquipped || {}
  };
}

